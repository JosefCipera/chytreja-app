import assert from 'node:assert/strict';
import { createLauncherHarness } from './ai-tester/launcher-render-harness.mjs';
const speechEvent = text => ({ results: [[{ transcript: text }]] });
const body = { mode:'ACT',text:'Dnešní odpověď',buttons:['Hotovo','Přeskočit'],expects_reply:false };
const ui = createLauncherHarness({ requestFlow:true,speech:true });
ui.configure({ response:{status:200,body} });
const recording = ui.startSpeech();
assert.equal(recording.lang,'cs-CZ');
assert.equal(recording.interimResults,false);
await recording.onresult(speechEvent('  Chci zhubnout.  '));
let state=ui.state();
assert.equal(state.echo,'Chci zhubnout.');
assert.equal(state.echo_label,'Přepis hlasu');
assert.equal(state.echo_visible,true);
assert.equal(state.draft,'','Clearing the composer does not clear the echo');
assert.equal(ui.storage().requests[0].text,'Chci zhubnout.');
assert.equal('input_echo' in ui.storage().requests[0],false,'UI metadata is not submitted to engine');
await recording.onresult(speechEvent('Duplicate result'));
assert.equal(ui.storage().requests.length,1,'Duplicate final callback cannot submit again');
recording.onend();
ui.configure({ response:{status:200,body:{mode:'EXPLAIN',text:'Vysvětlení',buttons:['Hotovo','Přeskočit']}} });
state=await ui.clickRequest('Proč?');
assert.equal(state.echo,'Chci zhubnout.');
assert.equal(state.echo_label,'Přepis hlasu','Navigation is not a new voice utterance');
const restored=createLauncherHarness({requestFlow:true});
restored.configure({session:ui.storage().session});
state=restored.render(ui.storage().response);
assert.equal(state.echo,'Chci zhubnout.');
assert.equal(state.echo_visible,true);
ui.configure({response:{status:200,body}});
state=await ui.submit('<img src=x onerror=alert(1)>');
assert.equal(state.echo,'<img src=x onerror=alert(1)>','Echo uses literal text, not HTML');
assert.equal(state.echo_label,'Tvoje zpráva');
const blocked=ui.startSpeech();
ui.render({mode:'SAFETY_CRITICAL',text:'Stop',buttons:[],expects_reply:false});
await blocked.onresult(speechEvent('Input after critical lock'));
assert.equal(ui.storage().requests.length,3,'Active recording cannot bypass critical terminal');
ui.idle();
const oldRecording=ui.startSpeech();
ui.invalidateSpeech();
await oldRecording.onresult(speechEvent('Stale user message'));
assert.equal(ui.storage().requests.length,3,'Invalidated speech never reaches request handler');
assert.equal(ui.state().echo_visible,false,'Reset clears visible input');
ui.idle();
assert.equal(ui.state().echo,'');
// An original voice request must keep its echo even when a later request waits
// behind it, or an unsent later draft is retained in the editable composer.
const retryUi=createLauncherHarness({requestFlow:true,speech:true});
retryUi.configure({response:{error:new Error('Offline')}});
await retryUi.startSpeech().onresult(speechEvent('Jsem nejistý při chůzi.'));
assert.equal(retryUi.state().echo_label,'Přepis hlasu');
const retry=retryUi.storage().session.pending_ai_retry;
retryUi.configure({response:{status:200,body:{mode:'HOLD',text:'Nejprve opakuj původní zprávu',
 buttons:['Zkusit znovu'],draft_text:'Chci zhubnout.',session_updates:{pending_ai_retry:retry}}}});
await retryUi.submit('Chci zhubnout.');
assert.equal(retryUi.state().echo,'Chci zhubnout.');
retryUi.configure({response:{status:200,body:{mode:'ACT',text:'Zpracováno',buttons:[],session_updates:{pending_ai_retry:null}}}});
state=await retryUi.clickRequest('Zkusit znovu');
assert.equal(state.echo,'Jsem nejistý při chůzi.');
assert.equal(state.echo_label,'Přepis hlasu','Retry echoes the replayed input, not a later waiting message');
assert.equal(state.draft,'Chci zhubnout.','Later draft is independent of the echo');
console.log('PASS: production speech callbacks retain exact submitted text across reply/nav/restore/retry; typed text stays literal, duplicates/stale speech are ignored and reset clears echo.');

